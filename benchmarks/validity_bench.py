# ── the checker ──────────────────────────────────────────────────────────────

def _forest_violations(df: pd.DataFrame, key: str, parent: str) -> int:
    """Rows that sit on a cycle of the self-reference (a manager chain that
    loops back to itself)."""
    up = dict(zip(df[key], df[parent]))
    bad = 0
    for start in df[key]:
        seen, cur, steps = set(), start, 0
        while cur is not None and not (isinstance(cur, float) and np.isnan(cur)) and steps <= len(up):
            if cur in seen:
                bad += 1
                break
            seen.add(cur)
            cur = up.get(cur)
            steps += 1
    return bad


def check(case: Case, tables: Dict[str, pd.DataFrame]) -> Dict[str, int]:
    v = {"missing_tables": 0, "pk_duplicates": 0, "fk_orphans": 0, "nulls": 0, "unique_duplicates": 0,
         "enum_violations": 0, "range_violations": 0, "check_violations": 0, "cycles": 0}
    for t in case.tables:
        df = tables.get(t.name)
        if df is None:
            v["missing_tables"] += 1
            continue
        if all(c in df for c in t.pk):
            v["pk_duplicates"] += int(df.duplicated(list(t.pk)).sum() + df[list(t.pk)].isna().any(axis=1).sum())
        for col, ptab, pcol in t.fks:
            parent = tables.get(ptab)
            if col not in df or parent is None:
                v["fk_orphans"] += len(df)
                continue
            vals = df[col].dropna()
            v["fk_orphans"] += int((~vals.isin(set(parent[pcol]))).sum())
        for col in t.not_null:
            v["nulls"] += int(df[col].isna().sum()) if col in df else len(df)
        for cols in t.unique:
            if all(c in df for c in cols):
                sub = df[list(cols)].dropna()
                v["unique_duplicates"] += int(sub.duplicated().sum())
        for col, allowed in t.enums.items():
            if col in df:
                v["enum_violations"] += int((~df[col].dropna().isin(allowed)).sum())
        for col, (lo, hi) in t.ranges.items():
            if col in df:
                x = pd.to_numeric(df[col], errors="coerce").dropna()
                if lo is not None:
                    v["range_violations"] += int((x < lo).sum())
                if hi is not None:
                    v["range_violations"] += int((x > hi).sum())
        for _, rule in t.checks.items():
            ok = rule(df).fillna(True)
            v["check_violations"] += int((~ok).sum())
        for col in t.acyclic:
            if col in df:
                v["cycles"] += _forest_violations(df, t.pk[0], col)
    return v


# ── contestants ──────────────────────────────────────────────────────────────

def misata_from_ddl(case: Case, seed: int) -> Dict[str, pd.DataFrame]:
    import misata
    cfg = misata.from_ddl(case.ddl, default_rows=1000)
    rows = {t.name: t.rows for t in case.tables}
    for t in cfg.tables:
        t.row_count = rows.get(t.name, t.row_count)
    cfg.seed = seed
    return misata.generate_from_schema(cfg)


def faker_script(case: Case, seed: int) -> Dict[str, pd.DataFrame]:
    """The script people write: one Faker or NumPy call per column, foreign
    keys drawn uniformly from the parent's ids, CHECK clauses not read."""
    from faker import Faker
    fake = Faker()
    Faker.seed(seed)
    rng = np.random.default_rng(seed)
    out: Dict[str, pd.DataFrame] = {}
    for t in case.tables:
        n = t.rows
        cols: Dict[str, object] = {}
        for k in t.pk:
            if len(t.pk) == 1:
                cols[k] = np.arange(1, n + 1)
        fk_cols = {c: (p, pc) for c, p, pc in t.fks}
        names = set(t.not_null) | set(fk_cols) | set(t.enums) | set(t.ranges) | set(t.pk)
        for chk in t.checks:
            names |= {w for w in chk.replace(">", " ").replace("=", " ").split() if w.isidentifier()}
        for u in t.unique:
            names |= set(u)
        for c in sorted(names - set(cols)):
            if c in fk_cols:
                p, pc = fk_cols[c]
                pool = out[p][pc].to_numpy() if p in out else np.arange(1, n + 1)
                cols[c] = rng.choice(pool, n)
            elif c in t.enums:
                cols[c] = [fake.word() for _ in range(n)]  # the script picks its own labels
            elif "email" in c:
                cols[c] = [fake.email() for _ in range(n)]
            elif c.endswith(("_at", "_date", "_on")) or c in ("check_in", "check_out"):
                cols[c] = pd.to_datetime(rng.integers(1_640_000_000, 1_720_000_000, n), unit="s")
            elif c in ("name", "label", "sku", "room_number"):
                cols[c] = [fake.word() for _ in range(n)]
            else:
                cols[c] = rng.integers(0, 1000, n)
        out[t.name] = pd.DataFrame(cols)
    return out


CONTESTANTS: Dict[str, Callable[[Case, int], Dict[str, pd.DataFrame]]] = {
    "misata_from_ddl": misata_from_ddl,
    "faker_script": faker_script,
}


def run(seed: int = 7) -> Dict:
    results = {}
    for case in CASES:
        for name, fn in CONTESTANTS.items():
            t0 = time.time()
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                tables = fn(case, seed)
            secs = time.time() - t0
            v = check(case, tables)
            rows = sum(len(df) for df in tables.values())
            results.setdefault(case.name, {})[name] = {"violations": v, "total": sum(v.values()),
                                                       "rows": rows, "seconds": round(secs, 2)}
    return results


def to_markdown(results: Dict) -> str:
    keys = ["pk_duplicates", "fk_orphans", "nulls", "unique_duplicates", "enum_violations",
            "range_violations", "check_violations", "cycles"]
    head = "| Schema | Generator | Rows | " + " | ".join(k.replace("_", " ") for k in keys) + " | Total | Seconds |"
    lines = [head, "|" + "---|" * (len(keys) + 5)]
    for case, by in results.items():
        for name, r in by.items():
            lines.append(f"| {case} | {name} | {r['rows']:,} | "
                         + " | ".join(f"{r['violations'][k]:,}" for k in keys)
                         + f" | **{r['total']:,}** | {r['seconds']} |")
    return "\n".join(lines)


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--json", help="also write the raw results here")
    args = ap.parse_args(argv)
    res = run(args.seed)
    print(to_markdown(res))
    if args.json:
        with open(args.json, "w") as fh:
            json.dump(res, fh, indent=2)
    bad = sum(r["total"] for r in (res[c]["misata_from_ddl"] for c in res))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
