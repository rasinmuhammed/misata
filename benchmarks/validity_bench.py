@dataclass
class Table:
    name: str
    rows: int
    pk: Sequence[str]
    fks: Sequence[Tuple[str, str, str]] = ()          # (column, parent table, parent column)
    not_null: Sequence[str] = ()
    unique: Sequence[Sequence[str]] = ()
    enums: Dict[str, Sequence[str]] = field(default_factory=dict)
    ranges: Dict[str, Tuple[Optional[float], Optional[float]]] = field(default_factory=dict)
    checks: Dict[str, Callable[[pd.DataFrame], pd.Series]] = field(default_factory=dict)
    acyclic: Sequence[str] = ()                       # self-references that must form a forest


@dataclass
class Case:
    name: str
    ddl: str
    tables: List[Table]


def _ts(df, c):
    return pd.to_datetime(df[c], errors="coerce")


