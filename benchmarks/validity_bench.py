"""Validity benchmark: does generated data obey its own schema?

Five SQL schemas with the constraints real databases declare (NOT NULL,
UNIQUE, composite keys, CHECK ranges and enums, column-to-column CHECKs,
self-references, a six-level foreign-key chain, a many-to-many junction).
Each is generated by Misata straight from the DDL, and by the script people
usually write instead: Faker or NumPy per column, foreign keys drawn
uniformly from the parent ids, no CHECKs.

The checker below restates every rule in plain pandas. It shares no code
with Misata, so a pass is not Misata grading itself.

    python benchmarks/validity_bench.py            # prints a Markdown table
    python benchmarks/validity_bench.py --json out.json
"""
